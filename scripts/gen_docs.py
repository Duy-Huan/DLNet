"""Regenerate the parts of doc/ that are derived from the code: doc/cli.md and doc/zoo.md.

python scripts/gen_docs.py          # write
python scripts/gen_docs.py --check  # exit 1 if doc/ is out of date (used by tests and release)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

HEADER = "<!-- generated by scripts/gen_docs.py: do not edit by hand -->\n"


def _parser():
    from dlnet import cli

    captured = {}
    real = argparse.ArgumentParser.parse_args

    def grab(self, *a, **k):
        captured["p"] = self
        raise SystemExit(0)

    argparse.ArgumentParser.parse_args = grab
    try:
        cli.main(["--version"])
    except SystemExit:
        pass
    finally:
        argparse.ArgumentParser.parse_args = real
    return captured["p"]


def cli_md() -> str:
    from dlnet import __version__

    p = _parser()
    sub = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    intro = (
        "Mọi lệnh chạy bằng `python -m dlnet <lệnh>` (hoặc `dlnet <lệnh>` sau khi cài). "
        "Hướng dẫn dùng: [user-guide.md](user-guide.md).\n"
    )
    out = [HEADER, f"# Tham chiếu lệnh (DLNet {__version__})\n", intro]
    helps = {a.dest: a.help for a in sub._choices_actions}
    for name, sp in sub.choices.items():
        out.append(f"## `dlnet {name}`\n\n{helps.get(name) or ''}\n")
        rows = []
        for a in sp._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            flags = ", ".join(f"`{s}`" for s in a.option_strings) or f"`{a.dest}`"
            default = (
                ""
                if a.default is None or a.default is False or a.default == argparse.SUPPRESS
                else f"`{a.default}`"
            )
            choices = f" (một trong: {', '.join(map(str, a.choices))})" if a.choices else ""
            text = (a.help or "").replace("|", "\\|").replace("\n", " ")
            rows.append(f"| {flags} | {'có' if a.required else ''} | {default} | {text}{choices} |")
        if rows:
            out.append("| Tùy chọn | Bắt buộc | Mặc định | Ý nghĩa |\n|---|---|---|---|")
            out += rows
        out.append("")
    return "\n".join(out) + "\n"


def zoo_md() -> str:
    from dlnet import __version__, zoo
    from dlnet.zoo.dense import DECODERS

    return (
        HEADER + f"# Danh mục module của zoo (DLNet {__version__})\n\n"
        f"{len(zoo.OPS)} module, {len(DECODERS)} decoder phân đoạn ({', '.join(DECODERS)}). "
        "Nguồn và kết quả đối chiếu với mã gốc: [THIRD_PARTY.md](../THIRD_PARTY.md). "
        "Kiểu tensor và combinator: [architecture.md](architecture.md#kho-module-zoo).\n\n"
        + zoo.describe()
        + "\n"
    )


FILES = {"cli.md": cli_md, "zoo.md": zoo_md}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for name, fn in FILES.items():
        path = ROOT / "doc" / name
        text = fn()
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
    if stale:
        print(f"doc/ is out of date: {stale}; run python scripts/gen_docs.py")
        return 1
    print("doc/ generated files: ok" if a.check else f"wrote {list(FILES)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
