class ZooNet(nn.Module):
    def __init__(self, body, head, in_dims, kl_weight=0.0):
        super().__init__()
        self.body, self.head, self.size, self.kl_weight = body, head, tuple(in_dims[-2:]), kl_weight
        # members of an ensemble head: in training the output is (B, k, out), one loss per member
        self.ensemble_k = head.k if head.mode == "ensemble" else 0

    def kl_loss(self):
        """Sum of the KL terms stored by variational modules in the last training forward pass (0 if none)."""
        kls = [m.last_kl for m in self.modules() if getattr(m, "last_kl", None) is not None]
        return sum(kls) if kls else None

    def forward(self, x):
        z = self.body(x)
        return self.head(z, x.shape[-2:]) if self.head.mode == "dense" else self.head(z)


class Graph(nn.Module):
    """A directed acyclic graph of blocks, as drawn in a paper: every node reads the output of one
    earlier node, or merges several (`concat` on the channel axis, `add`). Written by
    `{"op": "graph", "nodes": [{"id", "from", "op", ...}, ...], "out": id}` (dlnet/paper.py).

    `wiring[i] = (how, sources)`: how is "op" (apply mods[i] to the one source), "concat",
    "add" or "mul"; a source is the index of an earlier node, -1 for the input of the graph."""

    def __init__(self, mods, wiring, axis=1, out=-1):
        super().__init__()
        self.mods = nn.ModuleList([nn.Identity() if m is None else m for m in mods])
        self.wiring, self.axis, self.out = [(h, tuple(s)) for h, s in wiring], axis, out

    def forward(self, x):
        ys = []
        for m, (how, src) in zip(self.mods, self.wiring, strict=True):
            xs = [x if i < 0 else ys[i] for i in src]
            if how == "concat":
                ys.append(torch.cat(xs, self.axis))
            elif how == "add":
                ys.append(sum(xs[1:], xs[0]))
            elif how == "mul":
                y = xs[0]
                for t in xs[1:]:
                    y = y * t
                ys.append(y)
            else:
                ys.append(m(xs[0]))
        return ys[self.out]


class ChannelMerge(nn.Module):
    def __init__(self, cin, cout):
        super().__init__()
        self.channel_conv = nn.Conv1d(cin, cout, kernel_size=1)

    def forward(self, x):
        return self.channel_conv(x.transpose(1, 2)).transpose(1, 2)


class Channelaffinity(nn.Module):
    def __init__(self, dim, reduction=16):
        super().__init__()
        # dim // reduction may be 0 for narrow stages, as in the original (the gate is then sigmoid(bias))
        self.fc1, self.fc2 = nn.Linear(dim, dim // reduction), nn.Linear(dim // reduction, dim)

    def forward(self, x):
        return torch.sigmoid(self.fc2(F.relu(self.fc1(x.mean(dim=1))))).unsqueeze(1) * x


class FGEM(nn.Module):
    """FAHM frequency-domain embedding: rFFT2, block-diagonal complex layer + GELU + residual,
    soft-shrink, + spectrum, iFFT2, 1x1 conv, BN, GELU -> tokens (B, HW, embed_dim)."""

    def __init__(self, in_chans, embed_dim, n_groups=2, sparsity_threshold=0.01):
        super().__init__()
        if in_chans % n_groups:
            raise ValueError(f"FGEM: {in_chans} channels not divisible by {n_groups} groups")
        self.n_groups, self.block_size, self.sparsity_threshold = (
            n_groups,
            in_chans // n_groups,
            sparsity_threshold,
        )
        self.w1 = nn.Parameter(0.02 * torch.randn(2, n_groups, self.block_size, self.block_size))
        self.b1 = nn.Parameter(0.02 * torch.randn(2, n_groups, self.block_size))
        self.act = nn.GELU()
        self.proj = nn.Conv2d(in_chans, embed_dim, kernel_size=1)
        self.batch_norm = nn.BatchNorm2d(embed_dim)

    def forward(self, x):
        dtype = x.dtype
        x = x.float()
        b, c, h, w = x.shape
        f0 = torch.fft.rfft2(x, dim=(2, 3), norm="ortho")
        f = f0.reshape(b, self.n_groups, self.block_size, f0.shape[2], f0.shape[3])
        e = lambda a, m: torch.einsum("bkihw,kio->bkohw", a, m)
        re = (
            self.act(e(f.real, self.w1[0]) - e(f.imag, self.w1[1]) + self.b1[0, :, :, None, None])
            + f.real
        )
        im = (
            self.act(e(f.imag, self.w1[0]) + e(f.real, self.w1[1]) + self.b1[1, :, :, None, None])
            + f.imag
        )
        z = torch.view_as_complex(
            F.softshrink(torch.stack([re, im], dim=-1), lambd=self.sparsity_threshold).contiguous()
        )
        z = z.reshape(b, c, f0.shape[2], f0.shape[3]) + f0
        x = torch.fft.irfft2(z, s=(h, w), dim=(2, 3), norm="ortho").type(dtype)
        return self.act(self.batch_norm(self.proj(x))).flatten(2).transpose(1, 2)


def selective_scan(u, delta, A, B, C, D):
    """Sequential selective scan (mamba selective_scan_ref, input-dependent B and C, no gate here).

    u, delta: (b, d, l); A: (d, n); B, C: (b, n, l); D: (d). h_t = exp(delta A) h_{t-1} + delta B u,
    y_t = C h_t; output y + D u.
    """
    dA = torch.exp(torch.einsum("bdl,dn->bdln", delta, A))
    dBu = torch.einsum("bdl,bnl,bdl->bdln", delta, B, u)
    x = u.new_zeros(u.shape[0], A.shape[0], A.shape[1])
    ys = []
    # unbind, not dA[:, :, i]: the backward of each index op allocates a zero tensor as large as dA,
    # O(L^2) memory traffic (FAHM training step 13.8 s -> see tests/test_regression.py)
    for a_i, bu_i, c_i in zip(dA.unbind(2), dBu.unbind(2), C.unbind(2)):
        x = a_i * x + bu_i
        ys.append(torch.einsum("bdn,bn->bd", x, c_i))
    return torch.stack(ys, 2) + u * D[None, :, None]


class Mamba(nn.Module):
    """Mamba mixer (state-spaces/mamba mamba_simple.Mamba, slow path), pure PyTorch."""

    def __init__(self, d, d_state=16, d_conv=4, expand=2, dt_min=0.001, dt_max=0.1, dt_floor=1e-4):
        super().__init__()
        self.d_inner, self.d_state, self.dt_rank, self.d_conv = (
            expand * d,
            d_state,
            math.ceil(d / 16),
            d_conv,
        )
        self.in_proj = nn.Linear(d, 2 * self.d_inner, bias=False)
        self.conv1d = nn.Conv1d(
            self.d_inner, self.d_inner, d_conv, groups=self.d_inner, padding=d_conv - 1
        )
        self.x_proj = nn.Linear(self.d_inner, self.dt_rank + 2 * d_state, bias=False)
        self.dt_proj = nn.Linear(self.dt_rank, self.d_inner, bias=True)
        std = self.dt_rank**-0.5
        nn.init.uniform_(self.dt_proj.weight, -std, std)
        dt = torch.exp(
            torch.rand(self.d_inner) * (math.log(dt_max) - math.log(dt_min)) + math.log(dt_min)
        ).clamp(min=dt_floor)
        with torch.no_grad():
            self.dt_proj.bias.copy_(dt + torch.log(-torch.expm1(-dt)))  # inverse softplus
        self.A_log = nn.Parameter(
            torch.log(torch.arange(1, d_state + 1, dtype=torch.float32).repeat(self.d_inner, 1))
        )
        self.D = nn.Parameter(torch.ones(self.d_inner))
        self.out_proj = nn.Linear(self.d_inner, d, bias=False)

    def forward(self, h):  # (b, l, d)
        l = h.shape[1]
        x, z = self.in_proj(h).transpose(1, 2).chunk(2, 1)  # (b, d_inner, l)
        x = nn.functional.silu(self.conv1d(x)[..., :l])
        dt, B, C = self.x_proj(x.transpose(1, 2)).split(
            [self.dt_rank, self.d_state, self.d_state], -1
        )
        delta = nn.functional.softplus(self.dt_proj(dt).transpose(1, 2))  # dt_proj bias + softplus
        y = selective_scan(
            x, delta, -torch.exp(self.A_log), B.transpose(1, 2), C.transpose(1, 2), self.D
        )
        return self.out_proj((y * nn.functional.silu(z)).transpose(1, 2))


class PA(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.pa_conv = nn.Conv2d(dim, dim, kernel_size=3, padding=1, groups=dim)

    def forward(self, x):
        return x * torch.sigmoid(self.pa_conv(x))


class PreConv(nn.Module):
    """fahm.pre_conv: (1x1 conv, BN, GELU, 3x3 conv, BN, GELU) + GELU(1x1x1 conv3d(x))."""

    def __init__(self, c):
        super().__init__()
        self.act = nn.GELU()
        self.conv1, self.bn1 = nn.Conv2d(c, c, 1, bias=False), nn.BatchNorm2d(c)
        self.conv2, self.bn2 = nn.Conv2d(c, c, 3, padding=1, bias=False), nn.BatchNorm2d(c)
        self.proj = nn.Conv3d(
            1, 1, kernel_size=1, bias=False
        )  # the original's bn4 is never used: left out

    def forward(self, x):
        y = self.act(self.bn2(self.conv2(self.act(self.bn1(self.conv1(x))))))
        return y + self.act(self.proj(x.unsqueeze(1))).squeeze(1)


def rotate_half(x):
    x = x.reshape(*x.shape[:-1], -1, 2)
    x1, x2 = x.unbind(dim=-1)
    return torch.stack((-x2, x1), dim=-1).flatten(-2)


class RotaryEmbedding(nn.Module):
    """rope_spectral.RotaryEmbedding ('lang' frequencies) used as rotate_queries_or_keys on (B, N, D)."""

    def __init__(self, dim, theta=10000):
        super().__init__()
        self.register_buffer(
            "freqs", 1.0 / (theta ** (torch.arange(0, dim, 2)[: (dim // 2)].float() / dim))
        )

    def rotate_queries_or_keys(self, t):
        n = t.shape[-2]
        f = torch.arange(n, device=t.device, dtype=t.dtype)[:, None] * self.freqs.to(t.dtype)
        f = f.repeat_interleave(2, dim=-1).to(t)
        r = f.shape[-1]
        left, right = t[..., :r], t[..., r:]
        return torch.cat((left * f.cos() + rotate_half(left) * f.sin(), right), dim=-1)


class FAHM(nn.Module):
    """fahm.FAHM (3 stages) without its head: (B, C, s, s) -> mean token (B, embed_dims[-1])."""

    def __init__(
        self, in_chans, patch, n_groups=(2, 2, 2), embed_dims=(256, 128, 64), depths=(1, 1, 1)
    ):
        super().__init__()
        self.patch, self.depths = patch, depths
        self.new_bands = math.ceil(in_chans / n_groups[0]) * n_groups[0]
        self.channel_fusion = Channelaffinity(embed_dims[-1])
        self.postion = PA(in_chans)
        self.w = nn.Parameter(torch.ones(3))
        self.merge = nn.ModuleList()
        for i in range(3):
            setattr(
                self,
                f"patch_embed{i + 1}",
                FGEM(self.new_bands if i == 0 else embed_dims[i - 1], embed_dims[i], n_groups[i]),
            )
            setattr(self, f"norm{i + 1}", nn.LayerNorm(embed_dims[i]))
            setattr(self, f"rope{i + 1}", RotaryEmbedding(embed_dims[i] // 2))
            self.merge.append(ChannelMerge(embed_dims[i], embed_dims[-1]))
        self.mamba = nn.ModuleList(
            Mamba(embed_dims[i], 16, 4, 2) for i in range(3) for _ in range(depths[i])
        )
        self.pre_conv = PreConv(in_chans)

    def forward(self, x):
        b, c = x.shape[:2]
        x = self.postion(self.pre_conv(x))
        if self.new_bands > c:  # ReplicationPad3d on the channel axis
            x = torch.cat([x, x[:, -1:].expand(-1, self.new_bands - c, -1, -1)], 1)
        z, li = [], 0
        for i in range(3):
            x = getattr(self, f"patch_embed{i + 1}")(x)
            x = getattr(self, f"rope{i + 1}").rotate_queries_or_keys(x)
            for _ in range(self.depths[i]):
                x = self.mamba[li](x)
                li += 1
            x = getattr(self, f"norm{i + 1}")(x)
            z.append(self.channel_fusion(self.merge[i](x)))
            if i < 2:
                x = x.reshape(b, self.patch, self.patch, -1).permute(0, 3, 1, 2).contiguous()
        return (z[0] * self.w[0] + z[1] * self.w[1] + z[2] * self.w[2]).mean(dim=1)


class Head(nn.Module):
    """Global pooling + dropout + linear (cls), a 1x1 convolution per pixel (dense), or one output
    layer per ensemble member (ensemble: TabM, arXiv:2410.24210)."""

    def __init__(self, kind, dims, out_dim, mode="cls", dropout=0.0):
        super().__init__()
        self.kind, self.mode = kind, mode
        if mode == "ensemble":
            # tabm.LinearEnsemble: k separate linear layers on the k member representations (k, d).
            # Training: (B, k, out), one loss per member (core.Trainer); eval: the members' mean
            # probability (classification, as log) or mean value (out_dim = 1).
            if kind != "seq":
                raise ValueError("an ensemble head needs (members, features)")
            k, d = dims
            b = d**-0.5
            self.drop = nn.Dropout(dropout)
            self.weight = nn.Parameter(torch.empty(k, d, out_dim).uniform_(-b, b))
            self.bias = nn.Parameter(torch.empty(k, out_dim).uniform_(-b, b))
            self.k = k
            return
        if mode == "dense":
            if kind != "map":
                raise ValueError("dense prediction needs a map feature")
            self.f = nn.Sequential(nn.Dropout2d(dropout), nn.Conv2d(dims[0], out_dim, 1))
        else:
            feat = dims[1] if kind == "seq" else dims[0]
            self.f = nn.Sequential(nn.Dropout(dropout), nn.Linear(feat, out_dim))

    def forward(self, x, size=None):
        if self.mode == "ensemble":
            y = (self.drop(x).transpose(0, 1) @ self.weight).transpose(
                0, 1
            ) + self.bias  # (B, k, out)
            if self.training:
                return y
            if y.shape[-1] == 1:
                return y.mean(1)
            return torch.logsumexp(torch.log_softmax(y, -1), 1) - math.log(self.k)  # log mean prob
        if self.mode == "dense":
            y = self.f(x)
            return nn.functional.interpolate(y, size=size, mode="bilinear", align_corners=False) \
                if size is not None and y.shape[-2:] != size else y  # fmt: skip
        if self.kind == "seq":
            x = x.mean(1)
        elif self.kind != "vec":
            x = x.mean(tuple(range(2, x.dim())))
        return self.f(x)


