class ZooNet(nn.Module):
    def __init__(self, body, head, in_dims, kl_weight=0.0):
        super().__init__()
        self.body, self.head, self.size, self.kl_weight = body, head, tuple(in_dims[-2:]), kl_weight
        # members of an ensemble head: in training the output is (B, k, out), one loss per member
        self.ensemble_k = head.k if head.mode == "ensemble" else 0

    def kl_loss(self):
        """Sum of the KL terms stored by variational modules in the last training forward pass (0 if none)."""
        kls = [m.last_kl for m in self.modules() if getattr(m, "last_kl", None) is not None]
        return sum(kls) if kls else None

    def forward(self, x):
        z = self.body(x)
        return self.head(z, x.shape[-2:]) if self.head.mode == "dense" else self.head(z)


class Graph(nn.Module):
    """A directed acyclic graph of blocks, as drawn in a paper: every node reads the output of one
    earlier node, or merges several (`concat` on the channel axis, `add`). Written by
    `{"op": "graph", "nodes": [{"id", "from", "op", ...}, ...], "out": id}` (dlnet/paper.py).

    `wiring[i] = (how, sources)`: how is "op" (apply mods[i] to the one source), "concat",
    "add" or "mul"; a source is the index of an earlier node, -1 for the input of the graph."""

    def __init__(self, mods, wiring, axis=1, out=-1):
        super().__init__()
        self.mods = nn.ModuleList([nn.Identity() if m is None else m for m in mods])
        self.wiring, self.axis, self.out = [(h, tuple(s)) for h, s in wiring], axis, out

    def forward(self, x):
        ys = []
        for m, (how, src) in zip(self.mods, self.wiring, strict=True):
            xs = [x if i < 0 else ys[i] for i in src]
            if how == "concat":
                ys.append(torch.cat(xs, self.axis))
            elif how == "add":
                ys.append(sum(xs[1:], xs[0]))
            elif how == "mul":
                y = xs[0]
                for t in xs[1:]:
                    y = y * t
                ys.append(y)
            else:
                ys.append(m(xs[0]))
        return ys[self.out]


class _LayerNormalize(nn.Module):
    def __init__(self, dim, fn):
        super().__init__()
        self.norm, self.fn = nn.LayerNorm(dim), fn

    def forward(self, x):
        return self.fn(self.norm(x))


class _MLPBlock(nn.Module):
    def __init__(self, dim, hidden, dropout=0.1):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(dim, hidden),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden, dim),
            nn.Dropout(dropout),
        )

    def forward(self, x):
        return self.net(x)


class _Residual(nn.Module):
    def __init__(self, fn):
        super().__init__()
        self.fn = fn

    def forward(self, x):
        return self.fn(x) + x


class _SSFTTAttention(nn.Module):
    def __init__(self, dim, heads=8, dropout=0.1):
        super().__init__()
        self.heads, self.scale = heads, dim**-0.5
        self.to_qkv = nn.Linear(dim, dim * 3, bias=True)
        self.nn1, self.do1 = nn.Linear(dim, dim), nn.Dropout(dropout)

    def forward(self, x):
        b, n, d = x.shape
        q, k, v = (
            t.reshape(b, n, self.heads, -1).transpose(1, 2) for t in self.to_qkv(x).chunk(3, dim=-1)
        )
        attn = (torch.einsum("bhid,bhjd->bhij", q, k) * self.scale).softmax(dim=-1)
        out = torch.einsum("bhij,bhjd->bhid", attn, v).transpose(1, 2).reshape(b, n, d)
        return self.do1(self.nn1(out))


class _SSFTTTransformer(nn.Module):
    def __init__(self, dim, depth, heads, mlp_dim, dropout):
        super().__init__()
        self.layers = nn.ModuleList(
            nn.ModuleList([
                _Residual(_LayerNormalize(dim, _SSFTTAttention(dim, heads, dropout))),
                _Residual(_LayerNormalize(dim, _MLPBlock(dim, mlp_dim, dropout))),
            ])
            for _ in range(depth)
        )  # fmt: skip

    def forward(self, x):
        for attention, mlp in self.layers:
            x = mlp(attention(x))
        return x


class SSFTT(nn.Module):
    """SSFTTnet without its final linear layer: (B, C, H, W) -> class-token features (B, dim)."""

    def __init__(
        self, bands, num_tokens=4, dim=64, depth=1, heads=8, mlp_dim=8, dropout=0.1, emb_dropout=0.1
    ):
        super().__init__()
        self.L, self.cT = num_tokens, dim
        self.conv3d_features = nn.Sequential(
            nn.Conv3d(1, 8, (3, 3, 3)), nn.BatchNorm3d(8), nn.ReLU()
        )
        self.conv2d_features = nn.Sequential(
            nn.Conv2d(8 * (bands - 2), 64, (3, 3)), nn.BatchNorm2d(64), nn.ReLU()
        )
        self.token_wA = nn.Parameter(torch.empty(1, num_tokens, 64))
        self.token_wV = nn.Parameter(torch.empty(1, 64, dim))
        nn.init.xavier_normal_(self.token_wA)
        nn.init.xavier_normal_(self.token_wV)
        self.pos_embedding = nn.Parameter(torch.empty(1, num_tokens + 1, dim))
        nn.init.normal_(self.pos_embedding, std=0.02)
        self.cls_token = nn.Parameter(torch.zeros(1, 1, dim))
        self.dropout = nn.Dropout(emb_dropout)
        self.transformer = _SSFTTTransformer(dim, depth, heads, mlp_dim, dropout)

    def forward(self, x):
        x = self.conv3d_features(x.unsqueeze(1))  # (B, 8, C-2, H-2, W-2)
        b, c, d, h, w = x.shape
        x = self.conv2d_features(x.reshape(b, c * d, h, w))
        x = x.flatten(2).transpose(1, 2)  # (B, HW, 64)
        a = (
            torch.einsum("bij,bjk->bik", x, self.token_wA.transpose(1, 2))
            .transpose(1, 2)
            .softmax(dim=-1)
        )
        t = torch.einsum("bij,bjk->bik", a, torch.einsum("bij,bjk->bik", x, self.token_wV))
        x = torch.cat((self.cls_token.expand(b, -1, -1), t), dim=1) + self.pos_embedding
        return self.transformer(self.dropout(x))[:, 0]


class Head(nn.Module):
    """Global pooling + dropout + linear (cls), a 1x1 convolution per pixel (dense), or one output
    layer per ensemble member (ensemble: TabM, arXiv:2410.24210)."""

    def __init__(self, kind, dims, out_dim, mode="cls", dropout=0.0):
        super().__init__()
        self.kind, self.mode = kind, mode
        if mode == "ensemble":
            # tabm.LinearEnsemble: k separate linear layers on the k member representations (k, d).
            # Training: (B, k, out), one loss per member (core.Trainer); eval: the members' mean
            # probability (classification, as log) or mean value (out_dim = 1).
            if kind != "seq":
                raise ValueError("an ensemble head needs (members, features)")
            k, d = dims
            b = d**-0.5
            self.drop = nn.Dropout(dropout)
            self.weight = nn.Parameter(torch.empty(k, d, out_dim).uniform_(-b, b))
            self.bias = nn.Parameter(torch.empty(k, out_dim).uniform_(-b, b))
            self.k = k
            return
        if mode == "dense":
            if kind != "map":
                raise ValueError("dense prediction needs a map feature")
            self.f = nn.Sequential(nn.Dropout2d(dropout), nn.Conv2d(dims[0], out_dim, 1))
        else:
            feat = dims[1] if kind == "seq" else dims[0]
            self.f = nn.Sequential(nn.Dropout(dropout), nn.Linear(feat, out_dim))

    def forward(self, x, size=None):
        if self.mode == "ensemble":
            y = (self.drop(x).transpose(0, 1) @ self.weight).transpose(
                0, 1
            ) + self.bias  # (B, k, out)
            if self.training:
                return y
            if y.shape[-1] == 1:
                return y.mean(1)
            return torch.logsumexp(torch.log_softmax(y, -1), 1) - math.log(self.k)  # log mean prob
        if self.mode == "dense":
            y = self.f(x)
            return nn.functional.interpolate(y, size=size, mode="bilinear", align_corners=False) \
                if size is not None and y.shape[-2:] != size else y  # fmt: skip
        if self.kind == "seq":
            x = x.mean(1)
        elif self.kind != "vec":
            x = x.mean(tuple(range(2, x.dim())))
        return self.f(x)


