def dct_filters(h, w, mapper_x, mapper_y, channel):
    """MultiSpectralDCTLayer.get_dct_filter: channel groups, each one 2-D DCT-II basis function."""

    def f(pos, freq, n):
        r = math.cos(math.pi * freq * (pos + 0.5) / n) / math.sqrt(n)
        return r if freq == 0 else r * math.sqrt(2)

    out = torch.zeros(channel, h, w)
    part = channel // len(mapper_x)
    for i, (u, v) in enumerate(zip(mapper_x, mapper_y, strict=True)):
        for tx in range(h):
            for ty in range(w):
                out[i * part : (i + 1) * part, tx, ty] = f(tx, u, h) * f(ty, v, w)
    return out


class MultiSpectralAttention(nn.Module):
    """FcaNet MultiSpectralAttentionLayer: DCT pooling -> FC, ReLU, FC, sigmoid -> channel gates."""

    def __init__(self, channel, dct_h=7, dct_w=7, reduction=16, method="top16"):
        super().__init__()
        n = int(method[3:])
        xs, ys = (v[:n] for v in FCA_INDICES[method[:3]])
        xs, ys = [u * (dct_h // 7) for u in xs], [v * (dct_w // 7) for v in ys]
        if channel % n:
            raise ValueError(f"FcaNet: channels {channel} not divisible by {n} frequencies")
        self.dct_h, self.dct_w = dct_h, dct_w
        self.register_buffer("weight", dct_filters(dct_h, dct_w, xs, ys, channel))
        self.fc = nn.Sequential(
            nn.Linear(channel, channel // reduction, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear(channel // reduction, channel, bias=False),
            nn.Sigmoid(),
        )

    def forward(self, x):
        n, c, h, w = x.shape
        xp = (
            x
            if (h, w) == (self.dct_h, self.dct_w)
            else F.adaptive_avg_pool2d(x, (self.dct_h, self.dct_w))
        )
        y = (xp * self.weight).sum(dim=(2, 3))
        return x * self.fc(y).view(n, c, 1, 1)


class Head(nn.Module):
    """Global pooling + dropout + linear (cls), a 1x1 convolution per pixel (dense), or one output
    layer per ensemble member (ensemble: TabM, arXiv:2410.24210)."""

    def __init__(self, kind, dims, out_dim, mode="cls", dropout=0.0):
        super().__init__()
        self.kind, self.mode = kind, mode
        if mode == "ensemble":
            # tabm.LinearEnsemble: k separate linear layers on the k member representations (k, d).
            # Training: (B, k, out), one loss per member (core.Trainer); eval: the members' mean
            # probability (classification, as log) or mean value (out_dim = 1).
            if kind != "seq":
                raise ValueError("an ensemble head needs (members, features)")
            k, d = dims
            b = d**-0.5
            self.drop = nn.Dropout(dropout)
            self.weight = nn.Parameter(torch.empty(k, d, out_dim).uniform_(-b, b))
            self.bias = nn.Parameter(torch.empty(k, out_dim).uniform_(-b, b))
            self.k = k
            return
        if mode == "dense":
            if kind != "map":
                raise ValueError("dense prediction needs a map feature")
            self.f = nn.Sequential(nn.Dropout2d(dropout), nn.Conv2d(dims[0], out_dim, 1))
        else:
            feat = dims[1] if kind == "seq" else dims[0]
            self.f = nn.Sequential(nn.Dropout(dropout), nn.Linear(feat, out_dim))

    def forward(self, x, size=None):
        if self.mode == "ensemble":
            y = (self.drop(x).transpose(0, 1) @ self.weight).transpose(
                0, 1
            ) + self.bias  # (B, k, out)
            if self.training:
                return y
            if y.shape[-1] == 1:
                return y.mean(1)
            return torch.logsumexp(torch.log_softmax(y, -1), 1) - math.log(self.k)  # log mean prob
        if self.mode == "dense":
            y = self.f(x)
            return nn.functional.interpolate(y, size=size, mode="bilinear", align_corners=False) \
                if size is not None and y.shape[-2:] != size else y  # fmt: skip
        if self.kind == "seq":
            x = x.mean(1)
        elif self.kind != "vec":
            x = x.mean(tuple(range(2, x.dim())))
        return self.f(x)


