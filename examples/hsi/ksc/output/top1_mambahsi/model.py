class ZooNet(nn.Module):
    def __init__(self, body, head, in_dims, kl_weight=0.0):
        super().__init__()
        self.body, self.head, self.size, self.kl_weight = body, head, tuple(in_dims[-2:]), kl_weight
        # members of an ensemble head: in training the output is (B, k, out), one loss per member
        self.ensemble_k = head.k if head.mode == "ensemble" else 0

    def kl_loss(self):
        """Sum of the KL terms stored by variational modules in the last training forward pass (0 if none)."""
        kls = [m.last_kl for m in self.modules() if getattr(m, "last_kl", None) is not None]
        return sum(kls) if kls else None

    def forward(self, x):
        z = self.body(x)
        return self.head(z, x.shape[-2:]) if self.head.mode == "dense" else self.head(z)


class Escort(nn.Module):
    """x^2 / sum(x^2) over features (modular_deep_learning `escort`: a softmax alternative).

    The source divides by the exact sum; an epsilon is added here so a zero vector does not give NaN.
    """

    def forward(self, x):
        n = x.square()
        return n / (n.sum(1, keepdim=True) + 1e-8)


ACTS = {
    "relu": nn.ReLU, "gelu": nn.GELU, "swish": nn.SiLU, "tanh": nn.Tanh, "leaky": lambda: nn.LeakyReLU(0.1),
    "relu6": nn.ReLU6, "hswish": nn.Hardswish, "sigmoid": nn.Sigmoid, "escort": Escort, "identity": nn.Identity,
}  # fmt: skip


CONV = {1: nn.Conv1d, 2: nn.Conv2d, 3: nn.Conv3d}


def _same_pad(k, dilation):
    """'same' padding for an int or per-axis kernel size."""
    if isinstance(k, (list, tuple)):
        return tuple(dilation * (x - 1) // 2 for x in k)
    return dilation * (k - 1) // 2


BN = {1: nn.BatchNorm1d, 2: nn.BatchNorm2d, 3: nn.BatchNorm3d}


class FRN(nn.Module):
    """Filter Response Normalization + TLU (Singh & Krishnan, arXiv:1911.09737).

    Port of rasbt/deeplearning-models `FilterResponseNormalization`: x / sqrt(mean(x^2) + |eps|),
    then max(gamma x + beta, tau) with all parameters per channel.
    """

    def __init__(self, c, nd, eps=1e-6):
        super().__init__()
        shape = (1, c, *[1] * nd)
        self.gamma, self.beta = nn.Parameter(torch.ones(shape)), nn.Parameter(torch.zeros(shape))
        self.tau, self.eps = nn.Parameter(torch.zeros(shape)), nn.Parameter(torch.full((1,), eps))
        self.dims = tuple(range(2, 2 + nd))

    def forward(self, x):
        x = x * torch.rsqrt(x.square().mean(self.dims, keepdim=True) + self.eps.abs())
        return torch.max(self.gamma * x + self.beta, self.tau)


ND = {"ser": 1, "map": 2, "vol": 3}  # spatial dimensionality of the convolutional kinds


class _SeqBN(nn.Module):
    def __init__(self, c):
        super().__init__()
        self.bn = nn.BatchNorm1d(c)

    def forward(self, x):
        return self.bn(x.transpose(1, 2)).transpose(1, 2)


def norm_layer(kind, c, name):
    if kind in ("vec", "seq"):
        if name in ("layer", "group", "frn"):
            return nn.LayerNorm(c)
        if kind == "vec":
            return nn.BatchNorm1d(c)
        return _SeqBN(c)
    nd = ND[kind]
    if name == "batch":
        return BN[nd](c)
    if name == "layer":
        return nn.GroupNorm(1, c)
    if name == "group":
        g = next(g for g in (8, 4, 2, 1) if c % g == 0)
        return nn.GroupNorm(g, c)
    if name == "frn":
        return FRN(c, nd)
    raise ValueError(f"unknown norm {name!r}")


class ConvBNAct(nn.Sequential):
    def __init__(self, nd, i, o, k, s, groups, dilation, a, norm, pad="same"):
        pad = 0 if pad == "valid" else _same_pad(k, dilation)
        k, s = (tuple(k) if isinstance(k, list) else k), (tuple(s) if isinstance(s, list) else s)
        layers = [CONV[nd](i, o, k, s, pad, dilation=dilation, groups=groups, bias=norm == "none")]
        if norm != "none":
            layers.append(norm_layer({1: "ser", 2: "map", 3: "vol"}[nd], o, norm))
        if a != "identity":
            layers.append(ACTS[a]())
        super().__init__(*layers)


def selective_scan(u, delta, A, B, C, D):
    """Sequential selective scan (mamba selective_scan_ref, input-dependent B and C, no gate here).

    u, delta: (b, d, l); A: (d, n); B, C: (b, n, l); D: (d). h_t = exp(delta A) h_{t-1} + delta B u,
    y_t = C h_t; output y + D u.
    """
    dA = torch.exp(torch.einsum("bdl,dn->bdln", delta, A))
    dBu = torch.einsum("bdl,bnl,bdl->bdln", delta, B, u)
    x = u.new_zeros(u.shape[0], A.shape[0], A.shape[1])
    ys = []
    # unbind, not dA[:, :, i]: the backward of each index op allocates a zero tensor as large as dA,
    # O(L^2) memory traffic (FAHM training step 13.8 s -> see tests/test_regression.py)
    for a_i, bu_i, c_i in zip(dA.unbind(2), dBu.unbind(2), C.unbind(2)):
        x = a_i * x + bu_i
        ys.append(torch.einsum("bdn,bn->bd", x, c_i))
    return torch.stack(ys, 2) + u * D[None, :, None]


class Mamba(nn.Module):
    """Mamba mixer (state-spaces/mamba mamba_simple.Mamba, slow path), pure PyTorch."""

    def __init__(self, d, d_state=16, d_conv=4, expand=2, dt_min=0.001, dt_max=0.1, dt_floor=1e-4):
        super().__init__()
        self.d_inner, self.d_state, self.dt_rank, self.d_conv = (
            expand * d,
            d_state,
            math.ceil(d / 16),
            d_conv,
        )
        self.in_proj = nn.Linear(d, 2 * self.d_inner, bias=False)
        self.conv1d = nn.Conv1d(
            self.d_inner, self.d_inner, d_conv, groups=self.d_inner, padding=d_conv - 1
        )
        self.x_proj = nn.Linear(self.d_inner, self.dt_rank + 2 * d_state, bias=False)
        self.dt_proj = nn.Linear(self.dt_rank, self.d_inner, bias=True)
        std = self.dt_rank**-0.5
        nn.init.uniform_(self.dt_proj.weight, -std, std)
        dt = torch.exp(
            torch.rand(self.d_inner) * (math.log(dt_max) - math.log(dt_min)) + math.log(dt_min)
        ).clamp(min=dt_floor)
        with torch.no_grad():
            self.dt_proj.bias.copy_(dt + torch.log(-torch.expm1(-dt)))  # inverse softplus
        self.A_log = nn.Parameter(
            torch.log(torch.arange(1, d_state + 1, dtype=torch.float32).repeat(self.d_inner, 1))
        )
        self.D = nn.Parameter(torch.ones(self.d_inner))
        self.out_proj = nn.Linear(self.d_inner, d, bias=False)

    def forward(self, h):  # (b, l, d)
        l = h.shape[1]
        x, z = self.in_proj(h).transpose(1, 2).chunk(2, 1)  # (b, d_inner, l)
        x = nn.functional.silu(self.conv1d(x)[..., :l])
        dt, B, C = self.x_proj(x.transpose(1, 2)).split(
            [self.dt_rank, self.d_state, self.d_state], -1
        )
        delta = nn.functional.softplus(self.dt_proj(dt).transpose(1, 2))  # dt_proj bias + softplus
        y = selective_scan(
            x, delta, -torch.exp(self.A_log), B.transpose(1, 2), C.transpose(1, 2), self.D
        )
        return self.out_proj((y * nn.functional.silu(z)).transpose(1, 2))


class SpaMamba(nn.Module):
    """MambaHSI SpaMamba: Mamba over the pixels of each patch (row-major), GroupNorm, SiLU."""

    def __init__(self, channels, use_residual=True, group_num=4):
        super().__init__()
        self.use_residual = use_residual
        self.mamba = Mamba(channels, 16, 4, 2)
        self.proj = nn.Sequential(nn.GroupNorm(group_num, channels), nn.SiLU())

    def forward(self, x):
        b, c, h, w = x.shape
        y = self.mamba(x.permute(0, 2, 3, 1).reshape(b, h * w, c))
        y = self.proj(y.view(b, h, w, c).permute(0, 3, 1, 2).contiguous())
        return y + x if self.use_residual else y


class SpeMamba(nn.Module):
    """MambaHSI SpeMamba: each pixel's channels split into `token_num` tokens, Mamba over them."""

    def __init__(self, channels, token_num=4, use_residual=True, group_num=4):
        super().__init__()
        self.token_num, self.use_residual = token_num, use_residual
        self.group_channel_num = math.ceil(channels / token_num)
        self.channel_num = token_num * self.group_channel_num
        self.mamba = Mamba(self.group_channel_num, 16, 4, 2)
        self.proj = nn.Sequential(nn.GroupNorm(group_num, self.channel_num), nn.SiLU())

    def pad(self, x):
        b, c, h, w = x.shape
        return (
            x
            if c >= self.channel_num
            else torch.cat([x, x.new_zeros(b, self.channel_num - c, h, w)], 1)
        )

    def forward(self, x):
        xp = self.pad(x).permute(0, 2, 3, 1).contiguous()
        b, h, w, cp = xp.shape
        y = self.mamba(xp.view(b * h * w, self.token_num, self.group_channel_num))
        y = self.proj(y.view(b, h, w, cp).permute(0, 3, 1, 2).contiguous())
        return x + y if self.use_residual else y


class BothMamba(nn.Module):
    """MambaHSI BothMamba: softmax-weighted sum of the spatial and spectral branches, residual."""

    def __init__(self, channels, token_num=4, use_residual=True, group_num=4, use_att=True):
        super().__init__()
        self.use_att, self.use_residual = use_att, use_residual
        if use_att:
            self.weights = nn.Parameter(torch.ones(2) / 2)
        self.spa_mamba = SpaMamba(channels, use_residual, group_num)
        self.spe_mamba = SpeMamba(channels, token_num, use_residual, group_num)

    def forward(self, x):
        a, s = self.spa_mamba(x), self.spe_mamba(x)
        if self.use_att:
            w = torch.softmax(self.weights, 0)
            f = a * w[0] + s * w[1]
        else:
            f = a + s
        return f + x if self.use_residual else f


class Head(nn.Module):
    """Global pooling + dropout + linear (cls), a 1x1 convolution per pixel (dense), or one output
    layer per ensemble member (ensemble: TabM, arXiv:2410.24210)."""

    def __init__(self, kind, dims, out_dim, mode="cls", dropout=0.0):
        super().__init__()
        self.kind, self.mode = kind, mode
        if mode == "ensemble":
            # tabm.LinearEnsemble: k separate linear layers on the k member representations (k, d).
            # Training: (B, k, out), one loss per member (core.Trainer); eval: the members' mean
            # probability (classification, as log) or mean value (out_dim = 1).
            if kind != "seq":
                raise ValueError("an ensemble head needs (members, features)")
            k, d = dims
            b = d**-0.5
            self.drop = nn.Dropout(dropout)
            self.weight = nn.Parameter(torch.empty(k, d, out_dim).uniform_(-b, b))
            self.bias = nn.Parameter(torch.empty(k, out_dim).uniform_(-b, b))
            self.k = k
            return
        if mode == "dense":
            if kind != "map":
                raise ValueError("dense prediction needs a map feature")
            self.f = nn.Sequential(nn.Dropout2d(dropout), nn.Conv2d(dims[0], out_dim, 1))
        else:
            feat = dims[1] if kind == "seq" else dims[0]
            self.f = nn.Sequential(nn.Dropout(dropout), nn.Linear(feat, out_dim))

    def forward(self, x, size=None):
        if self.mode == "ensemble":
            y = (self.drop(x).transpose(0, 1) @ self.weight).transpose(
                0, 1
            ) + self.bias  # (B, k, out)
            if self.training:
                return y
            if y.shape[-1] == 1:
                return y.mean(1)
            return torch.logsumexp(torch.log_softmax(y, -1), 1) - math.log(self.k)  # log mean prob
        if self.mode == "dense":
            y = self.f(x)
            return nn.functional.interpolate(y, size=size, mode="bilinear", align_corners=False) \
                if size is not None and y.shape[-2:] != size else y  # fmt: skip
        if self.kind == "seq":
            x = x.mean(1)
        elif self.kind != "vec":
            x = x.mean(tuple(range(2, x.dim())))
        return self.f(x)


def build_model(*_unused) -> nn.Module:
    """The network. Arguments are ignored (older train.py passes arch, in_dim, out_dim)."""
    return ZooNet(
        nn.Sequential(
            ConvBNAct(2, 30, 32, 1, 1, 1, 1, "swish", "group", "same"),
            BothMamba(32, 4, True, 4, True),
            nn.AvgPool2d(2, 2, 0, ceil_mode=True),
            BothMamba(32, 4, True, 4, True),
            nn.Sequential(nn.AdaptiveAvgPool2d(1), nn.Flatten()),
        ),
        Head("vec", (32,), 13, "cls", 0.0),
        [30, 9, 9],
        0.001,
    )


