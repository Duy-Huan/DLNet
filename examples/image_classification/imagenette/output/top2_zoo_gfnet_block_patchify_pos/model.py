class ZooNet(nn.Module):
    def __init__(self, body, head, in_dims, kl_weight=0.0):
        super().__init__()
        self.body, self.head, self.size, self.kl_weight = body, head, tuple(in_dims[-2:]), kl_weight
        # members of an ensemble head: in training the output is (B, k, out), one loss per member
        self.ensemble_k = head.k if head.mode == "ensemble" else 0

    def kl_loss(self):
        """Sum of the KL terms stored by variational modules in the last training forward pass (0 if none)."""
        kls = [m.last_kl for m in self.modules() if getattr(m, "last_kl", None) is not None]
        return sum(kls) if kls else None

    def forward(self, x):
        z = self.body(x)
        return self.head(z, x.shape[-2:]) if self.head.mode == "dense" else self.head(z)


class Tokens(nn.Module):
    def forward(self, x):
        return x.flatten(2).transpose(1, 2)


class LearnedPos(nn.Module):
    def __init__(self, t, d):
        super().__init__()
        self.pe = nn.Parameter(torch.randn(1, t, d) * 0.02)

    def forward(self, x):
        return x + self.pe


def _from_last(x, kind):
    return x if kind == "seq" else x.movedim(-1, 1)


def _to_last(x, kind):
    """(B, C, *S) -> (B, *S, C) for the convolutional kinds; seq (B, T, D) already is."""
    return x if kind == "seq" else x.movedim(1, -1)


class _ChannelsLast(nn.Module):
    def __init__(self, body, kind):
        super().__init__()
        self.body, self.kind = body, kind

    def forward(self, x):
        return _from_last(self.body(_to_last(x, self.kind)), self.kind)


class GlobalFilter(nn.Module):
    """GFNet GlobalFilter for any number of spatial axes; input channels-last (B, *S, C)."""

    def __init__(self, dim, sizes):
        super().__init__()
        self.sizes = tuple(sizes)
        shape = (*self.sizes[:-1], self.sizes[-1] // 2 + 1, dim, 2)
        self.complex_weight = nn.Parameter(torch.randn(*shape, dtype=torch.float32) * 0.02)

    def forward(self, x):
        dtype, axes = x.dtype, tuple(range(1, 1 + len(self.sizes)))
        x = torch.fft.rfftn(x.float(), dim=axes, norm="ortho")
        x = x * torch.view_as_complex(self.complex_weight)
        x = torch.fft.irfftn(x, s=self.sizes, dim=axes, norm="ortho")
        return x.to(dtype)


class Mlp(nn.Module):
    """timm-style Mlp of GFNet / AFNO: fc1, GELU, dropout, fc2, dropout."""

    def __init__(self, d, hidden, drop=0.0):
        super().__init__()
        self.fc1, self.act, self.fc2 = nn.Linear(d, hidden), nn.GELU(), nn.Linear(hidden, d)
        self.drop = nn.Dropout(drop)

    def forward(self, x):
        return self.drop(self.fc2(self.drop(self.act(self.fc1(x)))))


class GFNetBlock(nn.Module):
    """GFNet Block: x + MLP(LN(GlobalFilter(LN(x)))) (one residual, as in the official code)."""

    def __init__(self, dim, sizes, mlp_ratio=4.0, drop=0.0):
        super().__init__()
        self.norm1 = nn.LayerNorm(dim)
        self.filter = GlobalFilter(dim, sizes)
        self.norm2 = nn.LayerNorm(dim)
        self.mlp = Mlp(dim, int(dim * mlp_ratio), drop)

    def forward(self, x):
        return x + self.mlp(self.norm2(self.filter(self.norm1(x))))


def mlp_block(i, hidden, out=None, out_act=None, bn=False, dropout=0.0):
    """FuxiCTR MLP_Block layers: Linear, [BN], ReLU, [Dropout] per hidden layer, [Linear, act]."""
    layers, dims = [], [i, *hidden]
    for a, b in itertools.pairwise(dims):
        layers.append(nn.Linear(a, b))
        if bn:
            layers.append(nn.BatchNorm1d(b))
        layers.append(nn.ReLU())
        if dropout > 0:
            layers.append(nn.Dropout(dropout))
    if out is not None:
        layers.append(nn.Linear(dims[-1], out))
    if out_act is not None:
        layers.append(out_act)
    return nn.Sequential(*layers)


class _MLPBlock(nn.Module):
    def __init__(self, *a, **k):
        super().__init__()
        self.mlp = mlp_block(*a, **k)  # attribute `mlp` as in FuxiCTR

    def forward(self, x):
        return self.mlp(x)


class FactorizationMachineBlock(nn.Module):
    def __init__(self, i, o, emb, rank_k=8, hidden=(32, 32), dropout=0.0):
        super().__init__()
        self.emb, self.o = emb, o
        self.proj_Y = nn.Parameter(torch.randn(i, rank_k))
        self.layer_norm = nn.LayerNorm(i * rank_k)
        self.mlp = _MLPBlock(
            i * rank_k, list(hidden), out=o * emb, out_act=nn.ReLU(), dropout=dropout
        )

    def forward(self, x):
        fm = torch.bmm(x, x.transpose(1, 2) @ self.proj_Y).flatten(1)
        return self.mlp(self.layer_norm(fm)).view(-1, self.o, self.emb)


class WuKongLayer(nn.Module):
    def __init__(self, i, lcb, fmb, emb, rank_k=8, hidden=(32, 32), dropout=0.0):
        super().__init__()
        self.fmb = FactorizationMachineBlock(i, fmb, emb, rank_k, hidden, dropout)
        self.lcb = nn.Module()
        self.lcb.linear = nn.Linear(i, lcb, bias=False)
        self.layer_norm = nn.LayerNorm(emb)
        if i != lcb + fmb:
            self.residual_proj = nn.Linear(i, lcb + fmb)

    def forward(self, x):
        out = torch.cat([self.fmb(x), self.lcb.linear(x.transpose(1, 2)).transpose(1, 2)], dim=1)
        res = (
            self.residual_proj(x.transpose(1, 2)).transpose(1, 2)
            if hasattr(self, "residual_proj")
            else x
        )
        return self.layer_norm(out + res)


class Head(nn.Module):
    """Global pooling + dropout + linear (cls), a 1x1 convolution per pixel (dense), or one output
    layer per ensemble member (ensemble: TabM, arXiv:2410.24210)."""

    def __init__(self, kind, dims, out_dim, mode="cls", dropout=0.0):
        super().__init__()
        self.kind, self.mode = kind, mode
        if mode == "ensemble":
            # tabm.LinearEnsemble: k separate linear layers on the k member representations (k, d).
            # Training: (B, k, out), one loss per member (core.Trainer); eval: the members' mean
            # probability (classification, as log) or mean value (out_dim = 1).
            if kind != "seq":
                raise ValueError("an ensemble head needs (members, features)")
            k, d = dims
            b = d**-0.5
            self.drop = nn.Dropout(dropout)
            self.weight = nn.Parameter(torch.empty(k, d, out_dim).uniform_(-b, b))
            self.bias = nn.Parameter(torch.empty(k, out_dim).uniform_(-b, b))
            self.k = k
            return
        if mode == "dense":
            if kind != "map":
                raise ValueError("dense prediction needs a map feature")
            self.f = nn.Sequential(nn.Dropout2d(dropout), nn.Conv2d(dims[0], out_dim, 1))
        else:
            feat = dims[1] if kind == "seq" else dims[0]
            self.f = nn.Sequential(nn.Dropout(dropout), nn.Linear(feat, out_dim))

    def forward(self, x, size=None):
        if self.mode == "ensemble":
            y = (self.drop(x).transpose(0, 1) @ self.weight).transpose(
                0, 1
            ) + self.bias  # (B, k, out)
            if self.training:
                return y
            if y.shape[-1] == 1:
                return y.mean(1)
            return torch.logsumexp(torch.log_softmax(y, -1), 1) - math.log(self.k)  # log mean prob
        if self.mode == "dense":
            y = self.f(x)
            return nn.functional.interpolate(y, size=size, mode="bilinear", align_corners=False) \
                if size is not None and y.shape[-2:] != size else y  # fmt: skip
        if self.kind == "seq":
            x = x.mean(1)
        elif self.kind != "vec":
            x = x.mean(tuple(range(2, x.dim())))
        return self.f(x)


