"""leaderboard.json -> a LaTeX table for a paper (booktabs), written as results.tex in the run.

    dlnet latex runs/indian_pines            # rewrite runs/indian_pines/results.tex, print it

Rows: the Top-K baselines DLNet found, the best classical reference, and every paper network
trained with the common protocol (`design --papers`). Columns: parameters, validation and test
(mean ± std over the runs). The best test score is bold. A paper network significantly worse or
better than the top-1 (paired t-test over the same runs, Holm-corrected, p < 0.05; dlnet/stats.py)
is marked with a dagger or a double dagger, explained in the caption.
"""

from __future__ import annotations

import json
from pathlib import Path

_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}  # fmt: skip


def esc(text) -> str:
    return "".join(_ESC.get(c, c) for c in str(text))


def _pm(mean, std, digits=4):
    if mean is None:
        return "--"
    s = f"{mean:.{digits}f}"
    return s if not std else s + f" $\\pm$ {std:.{digits}f}"


def _params(n):
    if not n:
        return "--"
    return f"{n / 1e6:.2f}M" if n >= 1e6 else f"{n / 1e3:.1f}K"


def rows(board: dict) -> list[dict]:
    """Uniform rows: {name, kind, params, val, val_std, test, test_std, mark}."""
    out = []
    for r in board.get("top_k", []):
        out.append({"name": r["name"].split("_", 1)[-1] if r["name"].startswith("top") else r["name"],
                    "kind": "dlnet", "params": r.get("params"), "val": r.get("val_mean"),
                    "val_std": r.get("val_std"), "test": (r.get("test") or {}).get("score"),
                    "test_std": r.get("test_std"), "mark": ""})  # fmt: skip
    refs = [x for x in board.get("reference", []) if isinstance(x, dict) and "test" in x]
    if refs:
        best = max(refs, key=lambda x: x.get("val", float("-inf")))
        out.append({"name": best["name"], "kind": "reference", "params": None, "val": best.get("val"),
                    "val_std": None, "test": best["test"].get("score"), "test_std": None, "mark": ""})  # fmt: skip
    for p in board.get("papers", []):
        c = p.get("common")
        if not c:
            continue
        v = (p.get("vs_top1") or {}).get("verdict")
        mark = {"worse": r"$^\dagger$", "better": r"$^\ddagger$"}.get(v, "")
        out.append({"name": p.get("paper", p.get("name")), "kind": "paper", "params": p.get("params"),
                    "val": c.get("val_mean"), "val_std": c.get("val_std"),
                    "test": (c.get("test") or {}).get("score"), "test_std": c.get("test_std"),
                    "mark": mark})  # fmt: skip
    return out


def table(board: dict, label: str = "tab:dlnet") -> str:
    rs = rows(board)
    metric = esc(board.get("metric", "score"))
    best = max((r["test"] for r in rs if r["test"] is not None), default=None)
    n = (board.get("top_k") or [{}])[0].get("n_runs", 1)
    lines = [
        r"% generated by dlnet latex from leaderboard.json; needs \usepackage{booktabs}",
        r"\begin{table}[t]",
        r"\centering",
        r"\begin{tabular}{llrcc}",
        r"\toprule",
        f"Network & Source & Params & Val {metric} & Test {metric} \\\\",
        r"\midrule",
    ]
    last = None
    for r in rs:
        if last and r["kind"] != last:
            lines.append(r"\midrule")
        last = r["kind"]
        test = _pm(r["test"], r["test_std"])
        if best is not None and r["test"] == best:
            test = f"\\textbf{{{test}}}"
        src = {"dlnet": "DLNet", "reference": "classical", "paper": "paper"}[r["kind"]]
        lines.append(f"{esc(r['name'])}{r['mark']} & {src} & {_params(r['params'])} & "
                     f"{_pm(r['val'], r['val_std'])} & {test} \\\\")  # fmt: skip
    caption = (
        f"Mean $\\pm$ std over {n} run(s) with the same seeds and splits for every network. "
        "Paper networks are trained with the protocol of the DLNet top-1. "
    )
    if any(r["mark"] for r in rs):
        caption += (
            r"$^\dagger$/$^\ddagger$: significantly worse/better than the DLNet top-1 "
            "(paired t-test on test, Holm-corrected, $p<0.05$)."
        )
    lines += [r"\bottomrule", r"\end{tabular}", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
              r"\end{table}"]  # fmt: skip
    return "\n".join(lines) + "\n"


def write(run_dir) -> Path:
    run = Path(run_dir)
    board_path = run / "leaderboard.json"
    if not board_path.exists():
        raise SystemExit(f"{board_path} not found: run `dlnet design ... --out {run}` first")
    board = json.loads(board_path.read_text())
    out = run / "results.tex"
    out.write_text(
        table(board, label=f"tab:{esc(run.name).replace(chr(92), '')}"), encoding="utf-8"
    )
    return out
